(() => {
  const API = (window.ATHENA_API_URL || '').replace(/\/$/, '');
  const $ = s => document.querySelector(s);
  const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  let current = null;

  $('#mode').textContent = API ? 'Live · AWS Lambda' : 'Demo mode · sample data';
  $('#mode').className = 'mode ' + (API ? 'live' : 'demo');

  async function call(method, path, body) {
    if (!API) return window.mockApi(method, path, body || {});
    const res = await fetch(API + path, {
      method, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined,
    });
    const json = await res.json().catch(() => ({}));
    return { ok: res.ok, status: res.status, body: json };
  }

  const status = (msg, kind = '') => { $('#status').textContent = msg; $('#status').className = 'status ' + kind; };
  const show = (sel, html) => { const el = $(sel); el.innerHTML = html; el.classList.remove('hidden'); };
  const hide = (...sels) => sels.forEach(s => $(s).classList.add('hidden'));
  function step(name) {
    const order = ['fetch', 'plan', 'review', 'email'];
    document.querySelectorAll('#steps li').forEach(li => {
      const i = order.indexOf(li.dataset.step), at = name === 'done' ? order.length : order.indexOf(name);
      li.className = i < at ? 'done' : i === at ? 'active' : '';
    });
  }

  function renderEmployee(e) {
    show('#employeeCard', `
      <h2>New joiner</h2>
      <div class="emp">
        <div class="avatar">${esc(e.name.split(' ').map(p => p[0]).join(''))}</div>
        <div><strong>${esc(e.name)}</strong> · ${esc(e.employeeId)}<br>
        <span class="muted">${esc(e.role)} · ${esc(e.team)} · ${esc(e.location)}</span><br>
        <span class="muted">Manager ${esc(e.manager)} · starts ${esc(e.startDate)}</span></div>
      </div>`);
  }

  function renderPlan(rec) {
    const p = rec.plan, locked = rec.status !== 'PENDING_REVIEW';
    const weeks = (p.weeks || []).map(w => `
      <div class="week"><h3>Week ${esc(w.week)} · ${esc(w.theme)}</h3>
        <ul>${(w.items || []).map(i => `<li><span class="day">${esc(i.day)}</span>
          <span><strong>${esc(i.title)}</strong> <span class="muted">(${esc(i.hours)}h · ${esc(i.moduleId)})</span><br>${esc(i.goal)}</span></li>`).join('')}</ul>
      </div>`).join('');
    show('#planCard', `
      <div class="plan-head"><h2>3-week onboarding plan</h2>
        <span class="badge ${esc(rec.status.toLowerCase())}">${esc(rec.status.replace('_', ' '))}</span></div>
      <p>${esc(p.summary)}</p>
      <p class="muted small">Plan ${esc(rec.planId)} · version ${esc(rec.version)} · generated by ${esc(rec.generatedBy)}</p>
      <div class="weeks">${weeks}</div>
      ${locked ? '' : `<div class="review">
        <input id="note" placeholder="Review note (optional)">
        <button class="btn" id="rejectBtn">Reject</button>
        <button class="btn primary" id="approveBtn">Approve plan</button></div>`}
      ${rec.status === 'APPROVED' ? '<div class="review"><button class="btn primary" id="sendBtn">Send email to new joiner</button></div>' : ''}`);
    if (!locked) {
      $('#approveBtn').onclick = () => review('APPROVED');
      $('#rejectBtn').onclick = () => review('REJECTED');
    }
    if (rec.status === 'APPROVED') $('#sendBtn').onclick = send;
    renderAudit(rec);
  }

  function renderAudit(rec) {
    show('#auditCard', `<h2>Audit trail</h2><ul class="audit">${(rec.audit || []).map(a =>
      `<li><code>${esc(a.at)}</code> <strong>${esc(a.action)}</strong> by ${esc(a.by)} ${a.note ? '· ' + esc(a.note) : ''}</li>`).join('')}</ul>`);
  }

  function emailHtml(rec) {
    const e = rec.employee, p = rec.plan;
    return `<p>Hi ${esc(e.name)},</p><p>${esc(p.summary)}</p>` + (p.weeks || []).map(w =>
      `<h4>Week ${esc(w.week)}: ${esc(w.theme)}</h4><ul>${(w.items || []).map(i =>
        `<li><b>${esc(i.day)}</b> — ${esc(i.title)} (${esc(i.hours)}h)</li>`).join('')}</ul>`).join('') +
      `<p>Your manager ${esc(e.manager)} will check in with you at the end of each week.</p>`;
  }

  async function generate(id) {
    current = null;
    hide('#employeeCard', '#planCard', '#emailCard', '#auditCard');
    $('#genBtn').disabled = true;
    try {
      step('fetch'); status('Fetching employee details…');
      const emp = await call('GET', `/employees/${encodeURIComponent(id)}`);
      if (!emp.ok) return status(emp.body.message || 'Employee not found', 'error');
      renderEmployee(emp.body);

      step('plan'); status('Selecting relevant training and drafting the plan…');
      const plan = await call('POST', '/plans', { employeeId: id });
      if (!plan.ok) return status(plan.body.message || 'Could not generate a plan', 'error');
      current = plan.body;
      step('review'); status('Plan ready. Review it, then approve or reject.', 'ok');
      renderPlan(current);
    } catch (err) {
      status('Something went wrong talking to the API. Please try again.', 'error');
      console.error(err);
    } finally {
      $('#genBtn').disabled = false;
    }
  }

  async function review(decision) {
    const res = await call('PUT', `/plans/${current.planId}`, { decision, reviewer: 'HR reviewer', note: $('#note')?.value || '' });
    if (!res.ok) return status(res.body.message, 'error');
    current = res.body;
    status(decision === 'APPROVED' ? 'Approved. You can now email the plan.' : 'Plan rejected. Generate a new one when ready.', decision === 'APPROVED' ? 'ok' : '');
    if (decision === 'APPROVED') step('email');
    renderPlan(current);
  }

  async function send() {
    const res = await call('POST', `/plans/${current.planId}/send`);
    if (!res.ok) return status(res.body.message, 'error');
    current = res.body.plan;
    renderPlan(current);
    step('done');
    status(res.body.mode === 'sent' ? `Email sent to ${res.body.to}.` : 'Email preview below (demo: nothing is actually sent).', 'ok');
    show('#emailCard', `<h2>${res.body.mode === 'sent' ? 'Email sent' : 'Email preview'}</h2>
      <div class="email"><p class="muted small">To: ${esc(res.body.to)}<br>Subject: ${esc(res.body.subject)}</p>
      <div class="email-body">${res.body.html || emailHtml(current)}</div></div>`);
  }

  $('#lookup').addEventListener('submit', e => { e.preventDefault(); generate($('#empId').value.trim()); });
  document.querySelectorAll('.chip').forEach(c => c.onclick = () => { $('#empId').value = c.dataset.id; generate(c.dataset.id); });
})();
